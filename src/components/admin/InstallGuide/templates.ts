import { isValidWixPrefix } from '@/lib/atlas/wixPrefix'

/**
 * The three things a volunteer pastes into Wix, generated from their own
 * service's key and prefix (#1055).
 *
 * **Generated, never hand-edited, and that is the point.** A router that calls
 * `/api/atlas/wix/*` has to agree with that endpoint about `status`, `redirect`,
 * `head` and `cacheSeconds`; the two live in this repo and change together. A
 * snippet in a wiki for a non-technical volunteer to adapt is the version that
 * silently stops agreeing — and the people installing this manage one site each,
 * across 13 national organisations, with no way to tell a stale snippet from a
 * current one.
 *
 * Pure strings, no React, so the Install tab renders them and
 * `tests/unit/wix-templates.spec.ts` pins them against the endpoint's own shape.
 */

/** What the generated snippets expect the router page's text element to be named. */
export const CONTENT_ELEMENT_ID = 'sahajAtlasContent'

/** The custom element's tag, which the widget's loader adopts wherever it sits. */
export const WIDGET_TAG_NAME = 'sahaj-atlas'

/** What the service needs to fill in before any of this can be generated. */
export interface InstallValues {
  /** The service's API key, as the reveal endpoint returned it. */
  apiKey: string
  /** The router's dynamic-page prefix, one lowercase path segment. */
  prefix: string
  /**
   * The same address with its slash, as a volunteer reads it — `/free-classes`.
   *
   * Carried beside `prefix` rather than derived at each use: the generated code
   * needs the bare segment and every instruction needs the address, and
   * composing one from the other in nine places is nine chances to drop the
   * slash in a sentence a volunteer then follows literally.
   */
  atlasUrl: string
  /** This CMS's own origin — where `/api/atlas/wix/*` lives. */
  cmsUrl: string
  /** The widget loader's origin, from `SAHAJATLAS_URL`. */
  widgetUrl: string
}

/**
 * A Velo function name from a router prefix.
 *
 * ⚠ **Wix derives the two function names from the prefix and will not find
 * them under any other spelling**, and a prefix is allowed hyphens where a
 * JavaScript identifier is not. So `free-classes` must export
 * `free_classes_Router`, not `free-classes_Router` — which is a syntax error —
 * and not `freeClasses_Router`, which parses and is never called.
 */
export function routerFunctionBase(prefix: string): string {
  return prefix.replace(/-/g, '_')
}

/**
 * The atlas URL a service's own `canonical.embed` implies, as a router prefix.
 *
 * ⚠ **The prefix and the mount must agree**, because the route endpoint decides
 * whether a page is self-canonical by comparing hosts and trusting that the
 * router sits at the mount the client designated. So the tab offers the mount's
 * own first segment rather than letting a volunteer pick freely, and validates
 * whatever they type.
 */
export function prefixFromMount(mount: string | null | undefined): string {
  const first = (mount ?? '').split('?')[0].split('/').filter(Boolean)[0] ?? ''
  const slug = first.toLowerCase().replace(/[^a-z0-9-]/g, '')
  return isValidWixPrefix(slug) ? slug : 'classes'
}

/** A value going into a JavaScript string literal in generated code. */
const js = (value: string): string => JSON.stringify(value)

/**
 * `backend/routers.js` — the router and the sitemap, for one prefix.
 *
 * ⚠ **Every failure still renders the page.** A timeout, a 5xx or a network
 * error gives the root a generic head and a sub-route `robots: noindex`, and
 * neither ever becomes a Wix error page: the widget boots client-side and shows
 * the real atlas regardless, so a visitor must never see our outage. An
 * unindexed sub-route is the conservative half of that — publishing a page with
 * a generic title under a specific URL is what teaches a crawler the wrong
 * thing.
 *
 * ⚠ **`notFound()` is reserved for a real 404**, which only our answer can
 * establish. An endpoint we could not reach is not evidence that the page does
 * not exist.
 */
export function wixRoutersTemplate(values: InstallValues): string {
  const { apiKey, prefix, cmsUrl } = values
  const base = routerFunctionBase(prefix)

  return `// Sahaj Atlas — generated by the Sahaj Atlas CMS. Do not edit by hand.
//
// Regenerate this file from the service's Install tab if the atlas URL or the
// API key changes. It has to agree with GET /api/atlas/wix/route about status,
// redirect, head and cacheSeconds, and the two are released together.

import { ok, notFound, redirect, WixRouterSitemapEntry } from 'wix-router'
import { fetch } from 'wix-fetch'

const CMS_URL = ${js(cmsUrl.replace(/\/+$/, ''))}
const API_KEY = ${js(apiKey)}
const PREFIX = ${js(prefix)}

// The router page's own name, as the Routers panel shows it. Wix routes to a
// page by this name, so it has to match what you called the page when you added
// the router — the Install tab's step names it for you.
const PAGE = ${js(prefix)}

// Short on purpose: a visitor waits for this before the page renders, and the
// widget shows the real atlas either way. A slow answer is worth less than a
// fast generic one.
const TIMEOUT_MS = 4000
const CACHE_TAGS = ['sahaj-atlas']

/** The page language, as a Multilingual site spells it in request.baseUrl. */
function languageOf(request) {
  const match = /\\/([a-z]{2}(?:-[a-zA-Z]{2})?)\\/?$/.exec(request.baseUrl || '')
  return match ? match[1] : ''
}

/** The atlas route, from the segments Wix hands us after the prefix. */
function routeOf(request) {
  const segments = (request.path || []).filter(Boolean)
  return segments.length === 0 ? '/' : '/' + segments.join('/')
}

async function askTheCms(path) {
  const response = await fetch(CMS_URL + path, {
    method: 'get',
    headers: { Authorization: 'clients API-Key ' + API_KEY },
    timeout: TIMEOUT_MS,
  })
  if (!response.ok) throw new Error('Sahaj Atlas CMS answered ' + response.status)
  return response.json()
}

/**
 * What to render when we could not reach the CMS.
 *
 * Never notFound(): only the CMS's own answer can establish that a page does
 * not exist, and an outage is not that answer.
 */
function degraded(route) {
  const head = { title: 'Free meditation classes' }
  if (route !== '/') head.metaTags = [{ name: 'robots', content: 'noindex' }]
  return ok(PAGE, { bodyHtml: '' }, head)
}

export async function ${base}_Router(request) {
  const route = routeOf(request)

  let answer
  try {
    answer = await askTheCms(
      '/api/atlas/wix/route?path=' +
        encodeURIComponent(route) +
        '&lang=' +
        encodeURIComponent(languageOf(request)),
    )
  } catch (error) {
    console.error('Sahaj Atlas: could not reach the CMS', error)
    return degraded(route)
  }

  if (answer.status === 404) return notFound()
  // answer.redirect is an atlas route, never a URL — this router owns the prefix.
  if (answer.status === 301) return redirect('/' + PREFIX + answer.redirect, '301')

  return ok(PAGE, answer.data, answer.head, {
    cache: { tags: CACHE_TAGS, ttl: answer.cacheSeconds },
  })
}

export async function ${base}_SiteMap(request) {
  let entries
  try {
    entries = await askTheCms('/api/atlas/wix/sitemap?prefix=' + encodeURIComponent(PREFIX))
  } catch (error) {
    console.error('Sahaj Atlas: could not reach the CMS for the sitemap', error)
    // An empty sitemap is how a site asks to be de-indexed, so a failure
    // returns nothing new rather than nothing at all — Wix keeps what it has.
    return []
  }

  return entries.map(function (entry) {
    const item = new WixRouterSitemapEntry(entry.url)
    item.pageName = PAGE
    item.title = entry.title
    item.url = entry.url
    item.lastModified = new Date(entry.lastmod)
    return item
  })
}
`
}

/**
 * The router page's own code — one element, filled from `getRouterData()`.
 *
 * ⚠ **`collapse()` in the browser, never `hide()`.** The crawlable text is
 * there for a crawler and for a visitor with no JavaScript; once the widget
 * boots it is duplicate content sitting above the map. `collapse()` takes it out
 * of the layout, where `hide()` would leave its box behind and push the map down
 * the page — and by the widget's own slot rules a map given less room than its
 * floor falls back to the compact card.
 */
export function wixPageCodeTemplate(): string {
  return `// Sahaj Atlas — generated by the Sahaj Atlas CMS. Do not edit by hand.

import { getRouterData } from 'wix-window-frontend'
import { rendering } from 'wix-rendering'

$w.onReady(function () {
  const data = getRouterData() || {}
  const content = $w('#${CONTENT_ELEMENT_ID}')

  content.html = data.bodyHtml || ''

  // In a browser the widget renders the real atlas, so the crawlable copy above
  // it is duplicate content. collapse() removes its box; hide() would not.
  if (rendering.env === 'browser') content.collapse()
})
`
}

/** What a volunteer types into the Custom Element panel, field by field. */
export interface CustomElementSettings {
  serverUrl: string
  tagName: string
}

/**
 * The Custom Element panel's two values.
 *
 * ⚠ **No `routing=` parameter.** The widget would then write the route into the
 * host page's URL itself, and on a Wix router that is the one thing it must not
 * do: the router already owns the path, so a widget rewriting it fights Wix's
 * own navigation. The route reaches the widget through the URL Wix is already
 * serving.
 */
export function wixCustomElementSettings(values: InstallValues): CustomElementSettings {
  const origin = values.widgetUrl.replace(/\/+$/, '')
  return {
    serverUrl: `${origin}/auto.js?key=${encodeURIComponent(values.apiKey)}`,
    tagName: WIDGET_TAG_NAME,
  }
}

/**
 * The one-line snippet a custom site or an iframe-only site pastes.
 *
 * `routing=path` only where the host serves the whole subtree — which is what
 * the custom-site track's catch-all requirement is about. An iframe-only site
 * gets neither, because it has no URLs of its own to route into.
 */
export function widgetSnippet(values: InstallValues, options: { routing: boolean }): string {
  const origin = values.widgetUrl.replace(/\/+$/, '')
  const routing = options.routing ? '&routing=path' : ''
  return `<script type="module" src="${origin}/auto.js?key=${encodeURIComponent(values.apiKey)}${routing}"></script>
<${WIDGET_TAG_NAME} style="display:block;height:80vh"></${WIDGET_TAG_NAME}>`
}
